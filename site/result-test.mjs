import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const context = vm.createContext({});
vm.runInContext(await readFile('site/browser-results.js', 'utf8'), context);
const { createEntries, pageEntries } = context.PhyloPrepResults;
const files = Array.from({ length: 67311 }, (_, index) => ({ name: `alignments/gene${index}.aln`, content: 'sequence' }));
files.push({ name: 'qc/codon/raw/alignment.details.tsv', content: 'QC' }, { name: 'matrices/codon/raw/supermatrix.fasta', content: 'matrix' }, { name: 'reports/sequence_changes.tsv', content: 'audit' });
const entries = createEntries(files), first = pageEntries(entries);
assert.equal(entries.length, 67314);
assert.equal(first.entries.length, 200);
assert.equal(first.entries[0].file.name, 'matrices/codon/raw/supermatrix.fasta');
assert.equal(first.entries[1].category, 'qc');
assert.equal(first.entries[0].file, files[67312]);
const qc = pageEntries(entries, { folder: 'qc' });
assert.equal(qc.total, 1); assert.equal(qc.entries[0].index, 67311);
assert.equal(pageEntries(entries, { query: 'gene123.aln' }).total, 1);
const last = pageEntries(entries, { page: 9999 });
assert.equal(last.start + last.entries.length, 67314);
assert.equal(pageEntries(entries, { query: 'no-such-file' }).entries.length, 0);
console.log('67,314-file priority, filtering, and bounded result-page checks passed.');
